# ── Prompt helpers ─────────────────────────────────────────────────────────────

# Every answer comes from a terminal. With stdin closed (a script, an agent), a read
# that failed used to end the script under set -e with exit 1 and no output at all
# (bugs review DOC-3); now it says so. A last line without a newline still counts.
eof_die() {
  printf '\nERROR: project-init.sh is interactive, and its input ended at: %s\n' "$1" >&2
  printf '       Run it in a terminal; ./project-init.sh <path> [name] prefills the first two answers.\n' >&2
  exit 1
}

prompt_with_default() {
  # Usage: prompt_with_default "Question" "default" varname
  local q="$1" def="$2" varname="$3" reply=""
  if [[ -n "$def" ]]; then
    read -r -p "$q [$def]: " reply || [[ -n "$reply" ]] || eof_die "$q"
    printf -v "$varname" '%s' "${reply:-$def}"
  else
    read -r -p "$q: " reply || [[ -n "$reply" ]] || eof_die "$q"
    printf -v "$varname" '%s' "$reply"
  fi
}

# Expand a user-typed host path: leading ~ / ~user, and $VAR / ${VAR} references.
# read -r takes input literally, so bash never expands these on its own.
# Deliberately does NOT eval the input (no command substitution) — this only
# ever substitutes an existing shell variable's value, so a stray "$(...)" in
# a pasted path can't execute anything.
expand_path() {
  local p="$1"

  # shellcheck disable=SC2088  # intentional: matching a literal leading ~ in the unexpanded input, not expanding it
  if [[ "$p" == "~" || "$p" == "~/"* ]]; then
    p="${HOME}${p:1}"
  elif [[ "$p" =~ ^~([^/]+)(.*)$ ]]; then
    local user="${BASH_REMATCH[1]}" rest="${BASH_REMATCH[2]}" userhome
    userhome="$(getent passwd "$user" 2>/dev/null | cut -d: -f6)"
    [[ -n "$userhome" ]] && p="${userhome}${rest}"
  fi

  local result="" rest="$p" var
  while [[ "$rest" =~ ^([^$]*)\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?(.*)$ ]]; do
    var="${BASH_REMATCH[2]}"
    result+="${BASH_REMATCH[1]}${!var-}"
    rest="${BASH_REMATCH[3]}"
  done
  result+="$rest"

  printf '%s' "$result"
}


# Parse a docker-style memory string (e.g. 512m, 2g, 1073741824, or -1) into bytes.
# Echoes the byte count (or "-1") and returns 0; returns 1 on parse failure.
mem_to_bytes() {
  local v="${1,,}"
  if [[ "$v" == "-1" ]]; then printf '%s' "-1"; return 0; fi
  if [[ "$v" =~ ^([0-9]+)([bkmg]?)$ ]]; then
    local num="${BASH_REMATCH[1]}" unit="${BASH_REMATCH[2]}"
    case "$unit" in
      b|"") printf '%s' "$num" ;;
      k)    printf '%s' "$(( num * 1024 ))" ;;
      m)    printf '%s' "$(( num * 1024 * 1024 ))" ;;
      g)    printf '%s' "$(( num * 1024 * 1024 * 1024 ))" ;;
    esac
    return 0
  fi
  return 1
}

# mem_le A B → true if both parse and A <= B.
mem_le() {
  local a b
  a="$(mem_to_bytes "$1")" || return 2
  b="$(mem_to_bytes "$2")" || return 2
  (( a <= b ))
}

# mem_ge A B → true if both parse and A >= B.
mem_ge() {
  local a b
  a="$(mem_to_bytes "$1")" || return 2
  b="$(mem_to_bytes "$2")" || return 2
  (( a >= b ))
}

