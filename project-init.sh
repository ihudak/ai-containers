# emit_env_list KEY VALUE — print KEY="VALUE" for a whitespace-separated list, one
# entry per line once there are two or more, so a long EXTRA_MOUNTS stays readable.
# load_env_defaults (sandbox-common.sh) joins the lines back into the one-line value.
# KEY may carry an `export ` prefix; it is printed as given. Also used by
# multiline-env.sh, which sources this file.
emit_env_list() {
  local key="$1" entry
  local -a entries=()
  read -r -a entries <<<"$2"
  if (( ${#entries[@]} < 2 )); then
    printf '%s="%s"\n' "$key" "$2"
    return 0
  fi
  printf '%s="\n' "$key"
  for entry in "${entries[@]}"; do printf '  %s\n' "$entry"; done
  printf '"\n'
}

# SOURCING GUARD — placed AFTER the globals above and BEFORE the first
# interactive prompt, deliberately. A sourcing caller (migrate-runme.sh) needs
# emit_launcher() *and* script_dir/projects_conf, but must not run the wizard:
# without this, `source project-init.sh` executed the whole thing as a side
# effect, rsyncing files and appending to projects.conf for whatever happened to
# be on stdin. Placing the guard any earlier leaves the caller with an unbound
# projects_conf; any later and the wizard has already started prompting.
# migrate-runme.sh's header already CLAIMED this guard existed.
# BY BEHAVIOUR, NOT BY STRING: `return` outside a function succeeds only in a
# sourced file. The string compare this replaced is correct only while no caller
# invokes this script by the same absolute path it gets sourced as — the accident
# that let build.sh recurse without bound (#218).
