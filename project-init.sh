# Portable launcher config (tracked/shareable — same on any machine). Loaded by
# sandbox-common.sh so build.sh / sandbox.sh / repo.sh / the thin runme.sh all agree.
# Precedence: inline env > sandbox.local.env > sandbox.env. Not overwritten by sync.
portable_group="$group_name"
# On a re-init, keep what is not re-prompted: SANDBOX_MODE, SANDBOX_WORKDIR and every
# key a user added. Writing open/.. over them turned a restricted project open with
# no trace — .ai-containers/ is gitignored by default (bugs review PRJ-3). The first
# value of a key wins, as in load_env_defaults. A workdir other than the project
# (..) is machine-local and the loader ignores it in sandbox.env; it is NOT copied
# into sandbox.local.env, because sandbox.env is committed and that would make what
# a committer wrote something this machine trusts (security review of 49ca941).
# It is named instead, with where it belongs. The old file is backed up like
# sandbox.local.env.
prev_mode=open kept_env=()
init_tmp="$(mktemp -d)" || { printf 'ERROR: mktemp -d failed\n' >&2; exit 1; }
trap 'rm -rf "$init_tmp"' EXIT
env_perms="$(_perms_new)"
if [[ -L "${dest}/sandbox.env" || ( -e "${dest}/sandbox.env" && ! -f "${dest}/sandbox.env" ) ]]; then
  _proj_note_skip "${dest}/sandbox.env" "it is not backed up or read, and is replaced"
elif [[ -e "${dest}/sandbox.env" ]] && ! _proj_read "${dest}/sandbox.env" "$init_tmp/sandbox.env" 16777216; then
  _proj_note_skip "${dest}/sandbox.env" "it is not backed up or read, and is replaced"
elif [[ -e "${dest}/sandbox.env" ]]; then
  env_perms="$_proj_perms"
  backup="${dest}/sandbox.env.pre-init"
  [[ -e "$backup" || -L "$backup" ]] && backup="${dest}/sandbox.env.pre-init.$(date -u +%Y%m%dT%H%M%SZ)"
  _proj_write "$init_tmp/sandbox.env" "$backup" "$env_perms" \
    || { printf 'ERROR: could not back up sandbox.env to %s\n' "$backup" >&2; exit 1; }
  printf '  Backed up existing sandbox.env → %s\n' "$(basename "$backup")"
  declare -A env_seen=()
  open="" open_keep=""
  while IFS= read -r line || [[ -n "$line" ]]; do
    # Inside a value that a bare opening quote began, the lines up to the one
    # that ends with `"` belong to it, as load_env_defaults reads them: carried
    # with their key, or dropped with it. Only the `KEY="` line was kept, so the
    # value never closed and every key after it was lost (review of REPO-12).
    if [[ -n "$open" ]]; then
      [[ -n "$open_keep" ]] && kept_env+=("$line")
      norm="${line%$'\r'}"; norm="${norm%"${norm##*[![:space:]]}"}"
      [[ "$norm" == *'"' ]] && open="" open_keep=""
      continue
    fi
    # Matched as load_env_defaults reads it — no CR, leading space or `export` —
    # and carried forward as written.
    norm="${line%$'\r'}"; norm="${norm#"${norm%%[![:space:]]*}"}"
    [[ "$norm" =~ ^export[[:space:]]+(.*)$ ]] && norm="${BASH_REMATCH[1]}"
    [[ "$norm" =~ ^([A-Za-z_][A-Za-z0-9_]*)=(.*)$ ]] || continue
    k="${BASH_REMATCH[1]}" v0="${BASH_REMATCH[2]}"   # before the next match overwrites them
    # A bare opening quote (trailing blanks allowed) opens a multi-line value.
    [[ "$v0" =~ ^\"[[:space:]]*$ ]] && open=1
    if [[ -n "${env_seen[$k]:-}" ]]; then open_keep=""; continue; fi
    env_seen[$k]=1
    open_keep=""
    case "$k" in
      SANDBOX_MODE)    prev_mode="$v0" ;;
      SANDBOX_WORKDIR)
        [[ "$v0" == .. ]] || printf '  NOTE: dropped SANDBOX_WORKDIR=%q from sandbox.env (only .. is portable); if this machine should use it, add it to sandbox.local.env yourself.\n' "$v0" ;;
      IMAGE_NAME|AI_CONTAINER_GROUP|CONTAINER_CPUS|CONTAINER_MEMORY|CONTAINER_MEMORY_RESERVATION|CONTAINER_MEMORY_SWAP) ;;  # re-prompted
      *) kept_env+=("$line"); [[ -n "$open" ]] && open_keep=1 ;;
    esac
  done < "$init_tmp/sandbox.env"
fi
{
  cat <<EOF
# sandbox.env — PORTABLE launcher config for ${project_name}'s AI sandbox.
IMAGE_NAME=${image_name}
AI_CONTAINER_GROUP=${portable_group}
CONTAINER_CPUS=${container_cpus}
CONTAINER_MEMORY=${container_memory}
CONTAINER_MEMORY_RESERVATION=${container_memory_reservation}
CONTAINER_MEMORY_SWAP=${container_memory_swap}
SANDBOX_MODE=${prev_mode}
SANDBOX_WORKDIR=..
EOF
  if (( ${#kept_env[@]} )); then
    printf '# Kept from the previous sandbox.env:\n'
    printf '%s\n' "${kept_env[@]}"
  fi
  cat <<'EOF'
# Machine-specific settings belong in sandbox.local.env (gitignored), NOT here:
#   EXTRA_MOUNTS="/abs/path /another:ro"   # host bind mounts (Linux-native; absolute paths)
#   REPOS="app:rw lib:ro"                  # named-volume repos (./repo.sh add; macOS perf)
#   SANDBOX_WORKDIR=@app                   # named-volume working dir (macOS)
EOF
} > "$init_tmp/new.env"
_proj_write "$init_tmp/new.env" "${dest}/sandbox.env" "$env_perms" \
  || { printf 'ERROR: could not write %s/sandbox.env\n' "$dest" >&2; exit 1; }
printf '  Wrote sandbox.env (portable config).\n'

# Machine-specific config → sandbox.local.env (gitignored). Always written (even with
# no EXTRA_MOUNTS/group-init answered) so every project has a documented place for
# machine-local overrides. AI_CONTAINER_GROUP_INIT is a host-referential one-time
# group-bootstrap directive (e.g. from:host), so it belongs here, not in the shared
# portable file; EXTRA_MOUNTS holds this machine's absolute bind paths.
#
# Back up an existing file first: this write is unconditional, and nothing here is
# ever re-asked — a hand-added REPOS=/SANDBOX_WORKDIR=@app/SANDBOX_MODE= would
# otherwise be silently lost. (sandbox.env is backed up too, and keeps what it is
# not re-asked for; see above.)
# NEVER clobber an existing backup. A fixed backup filename plus a plain `cp`
# means the SECOND re-init overwrites the first backup, and the original
# hand-edited EXTRA_MOUNTS/REPOS from before the first re-init is gone with no
# warning printed either time. Fall back to a timestamped name, which is both
# non-destructive and self-documenting about when it was taken.
# Through project-files.sh: a cp of a sandbox.local.env linked to a file of
# yours put that file in a backup the agent can read (PRJ-11). Its mode is kept
# for the backup and the new file, since it may hold a token.
local_perms="$(_perms_new)"
if [[ -L "${dest}/sandbox.local.env" || ( -e "${dest}/sandbox.local.env" && ! -f "${dest}/sandbox.local.env" ) ]]; then
  _proj_note_skip "${dest}/sandbox.local.env" "it is not backed up, and is replaced"
elif [[ -e "${dest}/sandbox.local.env" ]]; then
  backup="${dest}/sandbox.local.env.pre-init"
  if [[ -e "$backup" || -L "$backup" ]]; then
    backup="${dest}/sandbox.local.env.pre-init.$(date -u +%Y%m%dT%H%M%SZ)"
  fi
  if proj_backup "${dest}/sandbox.local.env" "$backup"; then
    local_perms="$_proj_perms"   # as read through the one open, not from the backup's name
    printf '  Backed up existing sandbox.local.env → %s\n' "$(basename "$backup")"
  else
    printf 'ERROR: could not back up sandbox.local.env to %s\n' "$backup" >&2; exit 1
  fi
fi
{
  cat <<'EOF'
# sandbox.local.env — THIS MACHINE's launcher config (gitignored, not shared).
# Overrides sandbox.env (loaded at higher precedence: inline env > sandbox.local.env > sandbox.env).
# Uncomment/add only what this machine or this one-off run needs:
#   EXTRA_MOUNTS="/abs/path /another:ro"   # host bind mounts (Linux-native; absolute paths)
#   REPOS="app:rw lib:ro"                  # named-volume repos (./repo.sh add; macOS perf)
#   SANDBOX_WORKDIR=@app                   # named-volume working dir (macOS)
#   AI_CONTAINER_GROUP_INIT=from:host      # one-time group bootstrap: clean|from:host|from:<group>
#   REPOS_PATH=/workspace                  # where in-container tools look for repos (default /workspace)
#
# SANDBOX_MODE overrides the portable default (currently "open" in sandbox.env). Options:
#   restricted  firewall enabled, NET_ADMIN/NET_RAW dropped from the agent shell
#   discovery   unrestricted egress + background pcap capture
#   open        unrestricted egress, no capture
#SANDBOX_MODE=open
EOF
  [[ -n "$group_init"   ]] && printf 'AI_CONTAINER_GROUP_INIT=%s\n' "$group_init"
  [[ -n "$extra_mounts" ]] && emit_env_list EXTRA_MOUNTS "$extra_mounts"
} > "$init_tmp/new.local.env"
_proj_write "$init_tmp/new.local.env" "${dest}/sandbox.local.env" "$local_perms" \
  || { printf 'ERROR: could not write %s/sandbox.local.env\n' "$dest" >&2; exit 1; }
printf '  Wrote sandbox.local.env (machine-specific).\n'

for dir in allowlist-domains.d allowlist-proxy-domains.d allowlist-cidrs.d; do
  custom="${dest}/${dir}/custom.txt"
  example="${dest}/${dir}/custom.txt.example"
  # Not -f: a dangling link is not a missing file, and is never written through.
  if [[ ! -e "$custom" && ! -L "$custom" && -f "$example" ]] \
     && _proj_write "${script_dir}/${dir}/custom.txt.example" "$custom" "$(_perms_new)"; then
    printf '  Created %s/%s/custom.txt from template.\n' "$(basename "$dest")" "$dir"
  fi
done

# Ensure the project's .ai-containers/.gitignore covers outputs + generated files:
# the same function sync runs, from project-files.sh.
ensure_inner_gitignore "$dest" >/dev/null
printf '  Ensured %s/.gitignore covers outputs and generated files.\n' "$(basename "$dest")"

# ── Write launcher ─────────────────────────────────────────────────────────────

write_launcher=1
if [[ -e "$launch_script" || -L "$launch_script" ]]; then
  ow=""; read -r -p "  $(basename "$launch_script") already exists. Overwrite? [y/N]: " ow || [[ -n "$ow" ]] || eof_die "overwriting $(basename "$launch_script")"
  case "$ow" in
    y|Y|yes|YES) write_launcher=1 ;;
    *) write_launcher=0 ;;
  esac
fi

if (( write_launcher )); then
  proj_emit_launcher "$launch_script" "$project_name" \
    || { printf 'ERROR: could not write %s\n' "$launch_script" >&2; exit 1; }
  printf '  Wrote %s\n' "$(basename "$launch_script")"
else
  printf '  Kept existing %s.\n' "$(basename "$launch_script")"
fi

# Keep the project's .ai-containers/ working copy out of the project's own repo.
ensure_ai_containers_ignored "$project_path"

# ── Register project ───────────────────────────────────────────────────────────

if [[ ! -f "$projects_conf" ]]; then
  cp "${script_dir}/projects.conf.example" "$projects_conf"
  printf '  Created projects.conf from template.\n'
fi

if grep -qxF "$project_path" "$projects_conf" 2>/dev/null; then
  printf '  %s already registered in projects.conf.\n' "$project_path"
else
  printf '%s\n' "$project_path" >> "$projects_conf"
  printf '  Registered %s in projects.conf.\n' "$project_path"
fi

# ── Next steps ─────────────────────────────────────────────────────────────────

printf '\nDone. Next steps:\n'
printf '  1. (Optional) Edit %s to choose components.\n' "${dest}/sandbox.conf"
printf '  2. Run: %s\n' "$launch_script"
