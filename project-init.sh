#!/usr/bin/env bash
# project-init.sh — interactively configure a project to use ai-containers.
#
# Prompts for image name, project location, container group (picked from the
# existing groups or named anew, with optional from-which-group bootstrap),
# CPU/memory limits, and extra mounts. Then
# copies the shared .ai-containers infrastructure into the project, registers
# it in projects.conf, and writes a ready-to-run runme.sh launcher modelled on
# ihudak-claude-plugins/.ai-containers/claude-plugins.sh.
#
# Most config vars (project_name, image_name, container_*, group_name, ...) are
# assigned indirectly via prompt_with_default's `printf -v "$varname"`. That
# indirect assignment is untraceable by the linter, which then reports them as
# referenced-but-unassigned; suppress that class file-wide (must precede the
# first command to apply to the whole file):
# shellcheck disable=SC2154
set -euo pipefail
unset CDPATH  # a relative cd follows it and prints the directory (bugs review GIT-17, GIT-20)
# shellcheck source=bash-floor.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/bash-floor.sh"
# shellcheck source=host-preflight.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/host-preflight.sh"
# shellcheck source=project-files.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/project-files.sh"

valid_group_name() {
  # Mirrors validate_group_name() in sandbox-common.sh.
  [[ "$1" =~ ^[a-z0-9][a-z0-9-]{0,31}$ ]]
}

# existing_groups — every group directory under ~/.ai-containers, one name per
# line. Only valid group names: anything else there cannot be selected anyway.
# LC_ALL=C so the menu numbering is the same under every host locale.
#
# That LC_ALL=C has NO regression test, deliberately, and this note is the
# reason: glibc's en_US.UTF-8 ignores punctuation at primary strength, so a
# dashed name (`a-x` vs `ab`) collates differently there — but neither
# environment the hermetic suite runs in can show it. macOS's sort orders that
# pair byte-wise under en_US.UTF-8 anyway, and the bash-floor container
# (ubuntu:22.04) ships only C, C.utf8 and POSIX. A test here would pass whether
# or not the LC_ALL=C survived, which is worse than none. Do not remove it on
# the grounds that nothing fails when you do.
existing_groups() {
  local d name
  [[ -d "$HOME/.ai-containers" ]] || return 0
  for d in "$HOME/.ai-containers"/*/; do
    [[ -d "$d" ]] || continue
    name="$(basename "$d")"
    # Not `host`, which every launch refuses, even as a leftover directory.
    if valid_group_name "$name" && [[ "$name" != host ]]; then printf '%s\n' "$name"; fi
  done | LC_ALL=C sort
}

# emit_launcher <path> <project-name> — write the thin runme.sh launcher.
#
# A FUNCTION, not an inline heredoc, because migrate-runme.sh sources this file
# to reuse it: one launcher template, two callers, no drift the next time the
# launcher changes. It previously WAS inline, and migrate-runme.sh called an
# emit_launcher() that had never existed — every run died at "command not found"
# (silently, because the source happened before its own argument parsing).
#
# CHANGING THE TEMPLATE: add it as launcher-templates/<n+1>.tmpl (the project name
# written @@PROJECT_NAME@@) and bump the "(launcher template n)" below to match.
# sync-to-projects.sh: `reconcile_launcher()` replaces a project's launcher only
# when it is one of those files, so a template missing from there strands every
# project on it; tests/test-launcher-templates.sh fails until the file is added
# (GAP-6). Keep line 2's "for <name>. Thin wrapper generated by" shape: that is
# where the name is read back from.
emit_launcher() {  # $1=destination path  $2=project name
  local dest_path="$1" proj_name="$2"
  cat > "$dest_path" <<EOF
#!/usr/bin/env bash
# runme.sh — launch the AI sandbox for ${proj_name}. Thin wrapper generated by
# project-init.sh. sync-to-projects.sh replaces it with the current template while it
# is unedited (launcher template 4); once you edit it, sync leaves it alone.
# Config lives in sandbox.env (portable) and sandbox.local.env (this machine);
# precedence inline > local > portable.
set -euo pipefail
# A CDPATH from your shell would send this cd to another project's launcher.
unset CDPATH
cd "\$(dirname "\${BASH_SOURCE[0]}")"

# Build-time GitHub token for private tool downloads. build.sh passes it to docker build
# as a BuildKit secret; sandbox.sh does NOT forward it into the container. Non-clobbering
# (an already-set token wins), gh-optional (absence degrades to "no token").
if command -v gh >/dev/null 2>&1; then
  : "\${GITHUB_TOKEN:=\$(gh auth token 2>/dev/null || true)}"
  export GITHUB_TOKEN
fi

# Version query: pure output, no build. MUST come before ./build.sh — asking
# what version this is should not build an image to answer.
case "\${1:-}" in
  -V|--version|version) exec ./sandbox.sh --version ;;
esac

./build.sh
#./build.sh --no-cache

# Network mode + working dir come from SANDBOX_MODE / SANDBOX_WORKDIR (sandbox.env /
# sandbox.local.env). One-off override:  SANDBOX_MODE=restricted ./runme.sh
# Or drive sandbox.sh directly:           ./sandbox.sh restricted @app
# Arguments are forwarded, so ./runme.sh restricted @app works too.
./sandbox.sh "\$@"
EOF
  chmod +x "$dest_path"
}

# proj_emit_launcher DEST NAME — emit_launcher into a private directory, then
# renamed in over DEST with the mode emit_launcher gave it, by
# project-files.sh: `_proj_write()` — `cat >` onto the old name wrote through a link there.
proj_emit_launcher() {
  local tmpd rc=0
  tmpd="$(mktemp -d)" || return 1
  emit_launcher "$tmpd/runme.sh" "$2" \
    && _proj_write "$tmpd/runme.sh" "$1" "$(_perms_of "$tmpd/runme.sh")" || rc=1
  rm -rf "$tmpd"
  return "$rc"
}


