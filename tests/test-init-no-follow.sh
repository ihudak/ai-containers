#!/usr/bin/env bash
# PRJ-11: project-init.sh (a re-init) and migrate-runme.sh never write through,
# or read through, a link the agent planted in a project. The agent can write
# the project, and its .ai-containers/ when that is a writable mount; a re-init
# over a sandbox.local.env linked to a 0600 file of yours copied that file into
# a .pre-init backup the agent could read, then overwrote it.
set -uo pipefail
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=portability.sh
source "$REPO_DIR/tests/portability.sh"
fails=0
pass() { printf 'PASS: %s\n' "$1"; }
fail() { printf 'FAIL: %s\n' "$1"; fails=$((fails+1)); }

TMP="$(mktemp -d)" || { printf 'SCAFFOLD-FAILED: mktemp -d\n'; exit 1; }; TMP_OWNER="$BASHPID"
# Only this process removes the fixture: the race case forks a child, which
# would inherit an unguarded trap (tests/test-exit-trap-ownership.sh).
trap '[[ "$BASHPID" == "$TMP_OWNER" ]] && rm -rf "$TMP"' EXIT
export HOME="$TMP/home"; mkdir -p "$HOME"
export GIT_CONFIG_GLOBAL="$TMP/home/.gitconfig" GIT_CONFIG_NOSYSTEM=1
unset VAULT_PATH SPECS_PATH DOCS_PATH ARCHITECTURE_REPO_PATH EXTRA_MOUNTS REPOS SANDBOX_ENV_FILE SANDBOX_WORKDIR AI_CONTAINER_GROUP

# An engine copy, so projects.conf and the shared files land in TMP.
E="$TMP/engine"; mkdir -p "$E"
# --no-owner/--no-group: as root (the bash-floor CI job, whose checkout is the
# runner's uid 1001) -a would hand $E itself to 1001, and git — with this test's
# empty global config — refuses it as "dubious ownership".
rsync -a --no-owner --no-group --exclude='.git' --exclude='tests' --exclude='docs' --exclude='projects.conf' "$REPO_DIR/" "$E/"
# A git repository with a tag, so its version is known and engine-version is written.
git -C "$E" init -q && git -C "$E" add -A \
  && git -C "$E" -c user.email=t@example.invalid -c user.name=t commit -qm engine && git -C "$E" tag v9.9.9 \
  || { printf 'SCAFFOLD-FAILED: engine repository\n'; exit 1; }

V="$TMP/victims"; mkdir -p "$V/dir-tools"
for f in env gi build runme conf ev; do printf 'victim %s\n' "$f" > "$V/$f"; chmod 600 "$V/$f"; done
printf 'GITHUB_TOKEN=s3cret-value\n' > "$V/secret"; chmod 600 "$V/secret"
snap() { local f; for f in "$V"/*; do [[ -f "$f" ]] && printf '%s %s %s\n' "$f" "$(p_sha1 "$f")" "$(p_stat_mode "$f")"; done; ls -A "$V/dir-tools"; }

# ── 1. A re-init over links the agent planted ──
proj="$TMP/proj"; d="$proj/.ai-containers"; mkdir -p "$d/allowlist-domains.d"; git -C "$proj" init -q
ln -s "$V/secret" "$d/sandbox.local.env"
ln -s "$V/env"    "$d/sandbox.env"
ln -s "$V/gi"     "$d/.gitignore"
ln -s "$V/build"  "$d/build.sh"
ln -s "$V/runme"  "$d/runme.sh"
ln -s "$V/conf"   "$d/sandbox.conf"
ln -s "$V/ev"     "$d/engine-version"
ln -s "$V/dir-tools" "$d/tools.d"
# GNU cp already refuses to write through a dangling link, so on GNU this one
# cannot tell the old `cp "$example" "$custom"` from the fix; a BSD cp can.
ln -s "$V/no-such-custom" "$d/allowlist-domains.d/custom.txt"
before="$(snap)"
# Answers: path, nine defaults (name … group-init menu, extra mounts), then
# "y" to overwrite the existing runme.sh.
out="$(printf '%s\n\n\n\n\n\n\n\n\n\ny\n' "$proj" | bash "$E/project-init.sh" 2>&1)"; rc=$?
[[ $rc -eq 0 ]] && pass "a re-init over planted links exits 0" || fail "a re-init over planted links exits 0 (rc=$rc): $out"
[[ "$before" == "$(snap)" ]] && pass "no file or directory a link pointed at was written or chmod'ed" \
  || fail "no file or directory a link pointed at was written or chmod'ed: $(diff <(printf '%s\n' "$before") <(snap))"
[[ ! -e "$V/no-such-custom" ]] && pass "a dangling custom.txt link creates nothing" || fail "a dangling custom.txt link creates nothing"
leak="$(grep -rl s3cret-value "$d" 2>/dev/null)"
[[ -z "$leak" ]] && pass "the linked secret is copied nowhere into the project" || fail "the linked secret is copied nowhere into the project: $leak"
for f in sandbox.local.env sandbox.env build.sh runme.sh .gitignore; do
  [[ -f "$d/$f" && ! -L "$d/$f" ]] || fail "$f is a file of its own after the re-init"
done
pass "sandbox.local.env, sandbox.env, build.sh, runme.sh and .gitignore are files of their own"
[[ -f "$d/engine-version" && ! -L "$d/engine-version" && "$(cat "$d/engine-version")" == v9.9.9 ]] \
  && pass "engine-version is a file of its own holding the engine's version" \
  || fail "engine-version is a file of its own holding the engine's version"
[[ -x "$d/runme.sh" ]] && grep -q 'Thin wrapper generated by' "$d/runme.sh" && pass "runme.sh is the generated launcher, executable" \
  || fail "runme.sh is the generated launcher, executable"
cmp -s "$d/build.sh" "$REPO_DIR/build.sh" && pass "build.sh is the engine's copy" || fail "build.sh is the engine's copy"
[[ -d "$d/tools.d" && ! -L "$d/tools.d" && -z "$(ls -A "$V/dir-tools")" ]] && pass "a linked tools.d is replaced by a real directory" \
  || fail "a linked tools.d is replaced by a real directory"
[[ -L "$d/sandbox.conf" && "$out" == *NOTE*sandbox.conf* ]] && pass "a linked sandbox.conf is kept and named" \
  || fail "a linked sandbox.conf is kept and named: $out"

# ── 2. An ordinary re-init still backs up and keeps modes ──
proj2="$TMP/proj2"; d2="$proj2/.ai-containers"; mkdir -p "$proj2"; git -C "$proj2" init -q
printf '%s\n\n\n\n\n\n\n\n\n\n' "$proj2" | bash "$E/project-init.sh" >/dev/null 2>&1
printf 'GITHUB_TOKEN=mine\n' >> "$d2/sandbox.local.env"; chmod 600 "$d2/sandbox.local.env"
out="$(printf '%s\n\n\n\n\n\n\n\n\n\ny\n' "$proj2" | bash "$E/project-init.sh" 2>&1)"; rc=$?
[[ $rc -eq 0 && -f "$d2/sandbox.local.env.pre-init" ]] && grep -qx 'GITHUB_TOKEN=mine' "$d2/sandbox.local.env.pre-init" \
  && [[ "$(p_stat_mode "$d2/sandbox.local.env.pre-init")" == 600 && "$(p_stat_mode "$d2/sandbox.local.env")" == 600 ]] \
  && pass "a re-init backs up sandbox.local.env with its 0600 mode, and keeps that mode" \
  || fail "a re-init backs up sandbox.local.env with its 0600 mode, and keeps that mode (rc=$rc, modes $(p_stat_mode "$d2/sandbox.local.env.pre-init") $(p_stat_mode "$d2/sandbox.local.env"))"
[[ -f "$d2/sandbox.env.pre-init" && -f "$d2/allowlist-domains.d/custom.txt" ]] \
  && pass "sandbox.env is backed up and custom.txt made from its template" \
  || fail "sandbox.env is backed up and custom.txt made from its template"

# sandbox.env keeps its mode through a re-init.
chmod 640 "$d2/sandbox.env"
printf '%s\n\n\n\n\n\n\n\n\n\ny\n' "$proj2" | bash "$E/project-init.sh" >/dev/null 2>&1
[[ "$(p_stat_mode "$d2/sandbox.env")" == 640 ]] && pass "a re-init keeps sandbox.env's mode (640)" \
  || fail "a re-init keeps sandbox.env's mode (640): $(p_stat_mode "$d2/sandbox.env")"
# A sandbox.env that cannot be read stops the re-init: replacing it lost its kept keys.
if [[ "$(id -u)" != 0 ]]; then
  printf 'PREVIEW_PORTS="3000"\n' >> "$d2/sandbox.env"; chmod 000 "$d2/sandbox.env"
  out="$(printf '%s\n\n\n\n\n\n\n\n\n\ny\n' "$proj2" | bash "$E/project-init.sh" 2>&1)"; rc=$?
  chmod 640 "$d2/sandbox.env"
  [[ $rc -ne 0 ]] && grep -q PREVIEW_PORTS "$d2/sandbox.env" && [[ "$out" == *ERROR*sandbox.env* ]] \
    && pass "an unreadable sandbox.env stops the re-init and is kept" \
    || fail "an unreadable sandbox.env stops the re-init and is kept (rc=$rc): $out"
else
  pass "an unreadable sandbox.env stops the re-init (not checkable as root)"
fi

# An inner .gitignore that cannot be backfilled is named, not reported as ensured.
rm -f "$d2/.gitignore"; mkdir "$d2/.gitignore"
out="$(printf '%s\n\n\n\n\n\n\n\n\n\ny\n' "$proj2" | bash "$E/project-init.sh" 2>&1)"
rmdir "$d2/.gitignore"
[[ "$out" == *NOTE*.gitignore* && "$out" != *"Ensured .ai-containers/.gitignore"* ]] \
  && pass "an inner .gitignore that cannot be backfilled is named, not reported as ensured" \
  || fail "an inner .gitignore that cannot be backfilled is named, not reported as ensured: $out"

# ── 2b. .ai-containers renamed and replaced by a link while the Overwrite
# prompt waits: nothing is written through the link ──
proj7="$TMP/proj7"; d7="$proj7/.ai-containers"; mkdir -p "$proj7" "$V/dir-swap"; git -C "$proj7" init -q
printf '%s\n\n\n\n\n\n\n\n\n\n' "$proj7" | bash "$E/project-init.sh" >/dev/null 2>&1
mkfifo "$TMP/answers"
( exec 3>"$TMP/answers"
  printf '%s\n\n\n\n\n\n\n\n\n\n' "$proj7" >&3
  for _ in $(seq 300); do grep -q 'Overwrite?' "$TMP/init7.out" 2>/dev/null && break; sleep 0.1; done
  mv "$d7" "$proj7/moved"; ln -s "$V/dir-swap" "$d7"
  printf 'y\n' >&3 ) &
bash "$E/project-init.sh" < "$TMP/answers" > "$TMP/init7.out" 2>&1; rc=$?
wait
[[ $rc -ne 0 && -z "$(ls -A "$V/dir-swap")" ]] && grep -q 'no longer the directory' "$TMP/init7.out" \
  && pass "a .ai-containers swapped for a link at the Overwrite prompt is not written through" \
  || fail "a .ai-containers swapped for a link at the Overwrite prompt is not written through (rc=$rc): $(ls -A "$V/dir-swap") $(tail -3 "$TMP/init7.out")"

# ── 2c. ... and replaced by another real directory: only the held descriptor
# tells the two apart (on macOS by inode, /dev/fd reporting fdescfs's device) ──
projS="$TMP/projS"; dS="$projS/.ai-containers"; mkdir -p "$projS"; git -C "$projS" init -q
printf '%s\n\n\n\n\n\n\n\n\n\n' "$projS" | bash "$E/project-init.sh" >/dev/null 2>&1
mkfifo "$TMP/answersS"
( exec 3>"$TMP/answersS"
  printf '%s\n\n\n\n\n\n\n\n\n\n' "$projS" >&3
  for _ in $(seq 300); do grep -q 'Overwrite?' "$TMP/initS.out" 2>/dev/null && break; sleep 0.1; done
  mv "$dS" "$projS/moved"; mkdir "$dS"
  printf 'y\n' >&3 ) &
bash "$E/project-init.sh" < "$TMP/answersS" > "$TMP/initS.out" 2>&1; rc=$?
wait
[[ $rc -ne 0 && -z "$(ls -A "$dS")" ]] && grep -q 'no longer the directory' "$TMP/initS.out" \
  && pass "a .ai-containers swapped for another directory at the Overwrite prompt is not written into" \
  || fail "a .ai-containers swapped for another directory at the Overwrite prompt is not written into (rc=$rc): $(ls -A "$dS") $(tail -3 "$TMP/initS.out")"

# ── 3. A .ai-containers that is itself a link is refused ──
proj3="$TMP/proj3"; mkdir -p "$proj3" "$V/dir-dest"; git -C "$proj3" init -q
ln -s "$V/dir-dest" "$proj3/.ai-containers"
out="$(printf '%s\n\n\n\n\n\n\n\n\n\n' "$proj3" | bash "$E/project-init.sh" 2>&1)"; rc=$?
[[ $rc -ne 0 && -z "$(ls -A "$V/dir-dest")" && "$out" == *".ai-containers"*link* ]] \
  && pass "project-init refuses a .ai-containers that is a link, writing nothing" \
  || fail "project-init refuses a .ai-containers that is a link, writing nothing (rc=$rc): $out"

# ── 4. migrate-runme.sh: reads the old launcher once, writes nothing through a link ──
proj4="$TMP/proj4"; d4="$proj4/.ai-containers"; mkdir -p "$d4"
printf '#!/usr/bin/env bash\nexport IMAGE_NAME=p4-image\nexport EXTRA_MOUNTS="/x:ro"\n./build.sh\n./sandbox.sh restricted ..\n' > "$d4/runme.sh"
ln -s "$V/secret" "$d4/sandbox.local.env"
ln -s "$V/env"    "$d4/sandbox.env"
before="$(snap)"
out="$(cd "$E" && bash ./migrate-runme.sh --projects-conf "$TMP/none.conf" "$proj4" </dev/null 2>&1)"; rc=$?
[[ $rc -eq 0 && "$before" == "$(snap)" ]] && pass "migrate-runme writes no file a link pointed at" \
  || fail "migrate-runme writes no file a link pointed at (rc=$rc): $out"
leak="$(grep -rl s3cret-value "$d4" 2>/dev/null)"
[[ -z "$leak" ]] && pass "migrate-runme copies the linked secret nowhere" || fail "migrate-runme copies the linked secret nowhere: $leak"
[[ -f "$d4/sandbox.env" && ! -L "$d4/sandbox.env" ]] && grep -qx 'IMAGE_NAME=p4-image' "$d4/sandbox.env" \
  && [[ -f "$d4/runme.sh.pre-migrate" && -x "$d4/runme.sh" ]] && grep -q 'Thin wrapper generated by' "$d4/runme.sh" \
  && pass "migrate-runme still migrates: sandbox.env, a thin runme.sh, the old one backed up" \
  || fail "migrate-runme still migrates: sandbox.env, a thin runme.sh, the old one backed up: $out"
# sandbox.local.env keeps its 0600 mode through a migration.
proj6="$TMP/proj6"; d6="$proj6/.ai-containers"; mkdir -p "$d6"
printf '#!/usr/bin/env bash\nexport IMAGE_NAME=p6\nexport EXTRA_MOUNTS="/y:ro"\n./sandbox.sh open ..\n' > "$d6/runme.sh"
printf 'GITHUB_TOKEN=mine\n' > "$d6/sandbox.local.env"; chmod 600 "$d6/sandbox.local.env"
(cd "$E" && bash ./migrate-runme.sh --projects-conf "$TMP/none.conf" "$proj6" </dev/null >/dev/null 2>&1)
[[ "$(p_stat_mode "$d6/sandbox.local.env")" == 600 && "$(p_stat_mode "$d6/sandbox.local.env.pre-migrate")" == 600 ]] \
  && pass "migrate-runme keeps sandbox.local.env's 0600 mode, in the backup and the new file" \
  || fail "migrate-runme keeps sandbox.local.env's 0600 mode ($(p_stat_mode "$d6/sandbox.local.env") $(p_stat_mode "$d6/sandbox.local.env.pre-migrate"))"
# An unreadable sandbox.env stops that project's migration and is kept.
if [[ "$(id -u)" != 0 ]]; then
  proj9="$TMP/proj9"; d9="$proj9/.ai-containers"; mkdir -p "$d9"
  printf '#!/usr/bin/env bash\nexport IMAGE_NAME=p9\n./sandbox.sh open ..\n' > "$d9/runme.sh"
  printf 'PREVIEW_PORTS="3000"\n' > "$d9/sandbox.env"; chmod 000 "$d9/sandbox.env"
  out="$(cd "$E" && bash ./migrate-runme.sh --projects-conf "$TMP/none.conf" "$proj9" </dev/null 2>&1)"
  chmod 644 "$d9/sandbox.env"
  grep -qx 'PREVIEW_PORTS="3000"' "$d9/sandbox.env" && [[ "$out" == *ERROR*sandbox.env* && ! -e "$d9/runme.sh.pre-migrate" ]] \
    && pass "an unreadable sandbox.env stops that project's migration and is kept" \
    || fail "an unreadable sandbox.env stops that project's migration and is kept: $out"
else
  pass "an unreadable sandbox.env stops the migration (not checkable as root)"
fi
# A .ai-containers that is itself a link is not migrated into.
proj8="$TMP/proj8"; mkdir -p "$proj8" "$V/dir-mig"
printf '#!/usr/bin/env bash\nexport IMAGE_NAME=p8\n./sandbox.sh open ..\n' > "$V/dir-mig/runme.sh"
ln -s "$V/dir-mig" "$proj8/.ai-containers"
out="$(cd "$E" && bash ./migrate-runme.sh --projects-conf "$TMP/none.conf" "$proj8" </dev/null 2>&1)"
[[ "$(ls -A "$V/dir-mig")" == runme.sh && "$out" == *"is a link"* ]] \
  && pass "migrate-runme refuses a .ai-containers that is a link, writing nothing" \
  || fail "migrate-runme refuses a .ai-containers that is a link, writing nothing: $(ls -A "$V/dir-mig") $out"
# An old launcher that is a link is not read through.
proj5="$TMP/proj5"; d5="$proj5/.ai-containers"; mkdir -p "$d5"
printf 'export IMAGE_NAME=from-a-link\n./sandbox.sh open ..\n' > "$V/fat"
ln -s "$V/fat" "$d5/runme.sh"
out="$(cd "$E" && bash ./migrate-runme.sh --projects-conf "$TMP/none.conf" "$proj5" </dev/null 2>&1)"; rc=$?
[[ ! -e "$d5/sandbox.env" && -L "$d5/runme.sh" && "$out" == *runme.sh*link* ]] \
  && pass "migrate-runme does not read a linked runme.sh, and names it" \
  || fail "migrate-runme does not read a linked runme.sh, and names it (rc=$rc): $out"

(( fails == 0 )) || { printf '%d failure(s)\n' "$fails"; exit 1; }
printf 'All init/migrate no-follow checks passed.\n'
